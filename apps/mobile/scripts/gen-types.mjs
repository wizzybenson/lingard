// Generate TypeScript types from the Pydantic contracts (SPEC §5.2). Run from apps/mobile: npm run gen:types
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { compile } from "json-schema-to-typescript";

const repo = resolve(import.meta.dirname, "../../..");
const file = join(mkdtempSync(join(tmpdir(), "lingard-schema-")), "contracts.json");
execFileSync("uv", ["run", "python", "-m", "lingard_contracts.schema_export", file, "--combined"], { cwd: repo, stdio: "inherit" });
const schema = JSON.parse(readFileSync(file, "utf8"));
const body = await compile(schema, "LingardContracts", {
  bannerComment: "// Generated by scripts/gen-types.mjs from packages/contracts. Do not edit.\n/* eslint-disable */",
  additionalProperties: false,
  unreachableDefinitions: true,
});
writeFileSync(resolve(import.meta.dirname, "../src/contracts/generated.ts"), body);
console.log("wrote src/contracts/generated.ts");
